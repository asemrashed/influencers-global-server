export interface EmailMessage {
  to: string;
  subject: string;
  text: string;
  html?: string;
}
export interface EmailProvider {
  readonly name: string;
  send(message: EmailMessage): Promise<void>;
}

export interface StorageProvider {
  readonly name: string;
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
  /**
   * A time-limited URL the browser can fetch directly, or null when this provider cannot hand out URLs
   * (local disk: stream the file through the API instead). Authorize the caller BEFORE asking for one.
   */
  getUrl(key: string, expiresInSeconds?: number): Promise<string | null>;
}

/** Keys are opaque, provider-agnostic paths generated by the server (never client filenames). */
export const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9/_.-]{0,254}$/;
export const DEFAULT_URL_TTL_SECONDS = 300;

/**
 * The AI capability. No adapter ships yet (AI_PROVIDER accepts only blank until a vendor is chosen), but the
 * routes already call this interface, so choosing a vendor means writing ONE adapter file. Every method must
 * treat its text arguments as untrusted DATA, never as instructions to follow.
 */
export interface AiProvider {
  readonly name: string;
  classifyMessage(input: { subject?: string; body: string }): Promise<{ category: string; confidence: number }>;
  summarizeThread(input: { messages: { from: string; body: string }[] }): Promise<{ summary: string }>;
  draftReply(input: { subject: string; messages: { from: string; body: string }[]; notes?: string }): Promise<{ subject: string; body: string }>;
  scoreMeeting(input: { title: string; description?: string }): Promise<{ score: number; recommendation: string }>;
  detectLead(input: { content: string; sourceType: string }): Promise<{ intentDetected: boolean; leadScore: number; suggestedNiche?: string }>;
}
