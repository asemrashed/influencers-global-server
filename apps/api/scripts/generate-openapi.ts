import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { loadApiEnv } from '@platform/config';
import { createApp } from '../src/app.js';
import { buildContainer } from '../src/container.js';

/** Writes `apps/api/openapi.json` and the typed schema used by `packages/api-client`. No database connection is made. */
const here = path.dirname(fileURLToPath(import.meta.url));
const env = loadApiEnv({
  NODE_ENV: 'test',
  DATABASE_URL: 'postgresql://placeholder:placeholder@localhost:5432/placeholder',
  APP_ENCRYPTION_KEY: Buffer.alloc(32, 1).toString('base64'),
  JOBS_ENABLED: 'false',
  LOG_LEVEL: 'silent',
  APP_NAME: 'Influencer Platform',
  APP_VERSION: '0.1.0',
});
const c = buildContainer(env);
const spec = createApp(c).openapi();

writeFileSync(path.join(here, '../openapi.json'), JSON.stringify(spec, null, 2) + '\n');
const ast = await openapiTS(spec as never);
const header = '/* eslint-disable */\n// GENERATED by `npm run client:generate` from apps/api/openapi.json. Do not edit by hand.\n\n';
writeFileSync(path.join(here, '../../../packages/api-client/src/schema.ts'), header + astToString(ast));
await c.db.$disconnect();
console.log(`openapi.json: ${Object.keys((spec as { paths: object }).paths).length} paths`);
